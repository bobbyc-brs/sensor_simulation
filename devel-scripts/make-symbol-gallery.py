#!/usr/bin/env python3
"""Write scenarios/symbol-gallery.json — every DIS frame and icon in one static view (CR-005 item 1).

Grid: one row per force (friendly, opposing, neutral, unknown) and one column per
type — the 12 catalogue types plus 6 raw types for the remaining frames. 18
columns are split into two bands of 9 so the grid fits a 2 NM view (furthest
cell ~2.4 NM; a 1280×800 GUI at 2 NM shows about ±2.6 NM vertically). Columns
0.4 NM and rows 0.35 NM apart: at the CR's ~0.3 NM the GUI's ~45 px symbols
touch at 2 NM. The ownship helicopter hovers between the bands.
Changes only that one file; re-runnable. Run from anywhere:
    python3 devel-scripts/make-symbol-gallery.py
"""
import json
import math
import pathlib

CENTRE = (45.40, -75.70)
COLUMN_NM = 0.4
ROW_NM = 0.35
COLUMNS_PER_BAND = 9
NM_M = 1852.0

FORCES = [('F', 'friendly'), ('O', 'opposing'), ('N', 'neutral'), ('U', 'unknown')]

# (cell label, type, altitude m) — catalogue names, then CR-005's raw types.
TYPES = [
    ('CAR', 'car', 70), ('TRUCK', 'cargo_truck', 70), ('BUS', 'bus', 70),
    ('SCHBUS', 'school_bus', 70), ('HORSE', 'horse', 70), ('RIDER', 'horse_with_rider', 70),
    ('TANK', 'tank', 70), ('AFV', 'afv', 70), ('UHELO', 'utility_helicopter', 300),
    ('AHELO', 'attack_helicopter', 300), ('PATROL', 'patrol_craft', 45), ('AIRLNR', 'civil_airliner', 1500),
    ('SUB', [1, 4, 39, 2, 0, 0, 0], 0),          # subsurface: submarine
    ('MILFW', [1, 2, 39, 1, 0, 0, 0], 1500),     # military fixed wing
    ('UAV', [1, 2, 39, 50, 0, 0, 0], 600),       # unmanned aerial vehicle
    ('SHIP', [1, 3, 39, 1, 0, 0, 0], 45),        # surface ship other than patrol craft
    ('PERSON', [3, 1, 39, 1, 0, 0, 0], 70),      # dismounted person
    ('UNK', [9, 1, 0, 0, 0, 0, 0], 70),          # unknown kind
]


def offset(lat, lon, east_nm, north_nm):
    """Flat-earth offset — fine over 2 NM."""
    dlat = north_nm * NM_M / 111320.0
    dlon = east_nm * NM_M / (111320.0 * math.cos(math.radians(lat)))
    return round(lat + dlat, 6), round(lon + dlon, 6)


def main():
    entities = [{
        'callsign': 'OWNSHIP', 'type': 'utility_helicopter', 'force': 'friendly', 'entity': 1,
        'ownship': True, 'speed_kts': 0, 'update_s': 1.0,
        'waypoints': [[CENTRE[0], CENTRE[1], 150]],
    }]
    number = 2
    for t_index, (label, entity_type, alt_m) in enumerate(TYPES):
        band, column = divmod(t_index, COLUMNS_PER_BAND)
        east = (column - (COLUMNS_PER_BAND - 1) / 2) * COLUMN_NM
        for f_index, (prefix, force) in enumerate(FORCES):
            # Band 0 above the ownship (rows 5..2 × spacing), band 1 below (rows -2..-5).
            row = 5 - f_index if band == 0 else -2 - f_index
            lat, lon = offset(*CENTRE, east, row * ROW_NM)
            entities.append({
                'callsign': f'{prefix}-{label}', 'type': entity_type, 'force': force, 'entity': number,
                'speed_kts': 0, 'motion': 'land',   # static: no motion model needed
                'waypoints': [[lat, lon, alt_m]],
            })
            number += 1

    scenario = {
        'name': 'symbol-gallery',
        'description': ('CR-005 item 1: every frame and icon at once — one row per force (F, O, N, U), '
                        'one column per type (12 catalogue + 6 raw types), two bands of 9 columns, '
                        f'columns {COLUMN_NM} NM and rows {ROW_NM} NM apart, static, around '
                        f'{CENTRE[0]}N {abs(CENTRE[1])}W. '
                        'Ownship 1.42.1 hovers between the bands. Generated by '
                        'devel-scripts/make-symbol-gallery.py. Runs until stopped.'),
        'defaults': {'site': 1, 'app': 42, 'update_s': 1.0},
        'entities': entities,
    }
    out = pathlib.Path(__file__).resolve().parent.parent / 'scenarios' / 'symbol-gallery.json'
    out.write_text(json.dumps(scenario, indent=1) + '\n', encoding='utf-8')
    print(f'wrote {out} — {len(entities)} entities')


if __name__ == '__main__':
    main()
